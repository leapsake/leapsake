const { withAppDelegate } = require("@expo/config-plugins");

// Excludes `<Documents>/SQLite` from iOS backup (the app's README → Layout);
// throws rather than skip when its anchor or a Swift AppDelegate is missing.

// Unique in the SDK 56 template, unlike `didFinishLaunchingWithOptions`.
const CALL_ANCHOR = "let delegate = ReactNativeDelegate()";

// The helper's name, whose presence makes a second prebuild a no-op.
const MARKER = "leapsakeExcludeStoreFromBackup";

const HELPER = `

// MARK: - Leapsake store backup exclusion
//
// Injected by plugins/with-store-backup-exclusion.js — edit it there, not here: this
// file is regenerated by \`expo prebuild\` and any change made directly is lost.
//
// Runs on every launch rather than only the first. The flag lives on the directory, so
// a directory that was removed and recreated would otherwise come back un-excluded.
// Creating it here is deliberate too: \`setResourceValues\` fails on a path that does not
// exist, and on a fresh install expo-sqlite has not made it yet.
private func ${MARKER}() {
  let fileManager = FileManager.default
  guard let documents = fileManager.urls(for: .documentDirectory, in: .userDomainMask).first else {
    NSLog("[Leapsake] no Documents directory found; the store was NOT excluded from backup")
    return
  }
  var storeDirectory = documents.appendingPathComponent("SQLite", isDirectory: true)
  do {
    if !fileManager.fileExists(atPath: storeDirectory.path) {
      try fileManager.createDirectory(at: storeDirectory, withIntermediateDirectories: true)
    }
    var values = URLResourceValues()
    values.isExcludedFromBackup = true
    try storeDirectory.setResourceValues(values)
  } catch {
    NSLog("[Leapsake] the store was NOT excluded from backup: \\(error)")
  }
}
`;

/** @type {import("@expo/config-plugins").ConfigPlugin} */
const withStoreBackupExclusion = (config) =>
  withAppDelegate(config, (mod) => {
    const { language } = mod.modResults;
    if (language !== "swift") {
      throw new Error(
        `with-store-backup-exclusion: expected a Swift AppDelegate, got "${language}". ` +
          "Re-point this plugin rather than letting the store be backed up.",
      );
    }

    if (mod.modResults.contents.includes(MARKER)) return mod;

    if (!mod.modResults.contents.includes(CALL_ANCHOR)) {
      throw new Error(
        `with-store-backup-exclusion: could not find the anchor "${CALL_ANCHOR}" in ` +
          "AppDelegate.swift, so the store would be backed up in the clear. The SDK " +
          "template has changed — re-point the anchor in " +
          "apps/mobile/plugins/with-store-backup-exclusion.js.",
      );
    }

    mod.modResults.contents =
      mod.modResults.contents.replace(
        CALL_ANCHOR,
        `${MARKER}()\n\n    ${CALL_ANCHOR}`,
      ) + HELPER;

    return mod;
  });

module.exports = withStoreBackupExclusion;
